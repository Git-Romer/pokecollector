"""Shared card upsert helper."""

from __future__ import annotations

import datetime

from sqlalchemy.orm import Session

from models import Card, ImageCache, Set
from services.price_utils import preserve_existing_prices_for_invalid_update

PARTIAL_NULL_CLEAR_FIELDS = frozenset({"data_source_lang"})


def _apply_set_digital_flag(db: Session, card_data: dict) -> None:
    if card_data.get("is_digital") or not card_data.get("set_id"):
        return
    set_lang = card_data.get("lang") or "en"
    set_row = db.query(Set.is_digital).filter(
        Set.tcg_set_id == card_data["set_id"],
        Set.lang == set_lang,
    ).first()
    if set_row and set_row[0]:
        card_data["is_digital"] = True


def _is_price_state_field(key: str) -> bool:
    return key.startswith("price_") or key.startswith("last_price_sync_")


def update_existing_card(
    existing: Card,
    card_data: dict,
    *,
    partial: bool = False,
    metadata_only: bool = False,
) -> Card:
    """Apply a full, partial, or catalogue-only payload to an existing card.

    ``data_source_lang`` is generated by the fallback layer, not inferred from
    a missing TCGdex field. A native brief row explicitly clears that marker so
    later sibling-language fallback cannot overwrite the native row.
    """
    for key, value in card_data.items():
        if key == "id" or (metadata_only and _is_price_state_field(key)):
            continue
        if partial and value is None and key not in PARTIAL_NULL_CLEAR_FIELDS:
            continue
        setattr(existing, key, value)
    return existing


def upsert_card(
    db: Session,
    card_data: dict,
    *,
    partial: bool = False,
    metadata_only: bool = False,
) -> Card:
    """Upsert card data; partial and metadata-only modes preserve other fields."""
    existing = db.query(Card).filter(Card.id == card_data["id"]).first()
    card_data["updated_at"] = datetime.datetime.utcnow()
    _apply_set_digital_flag(db, card_data)
    if not metadata_only:
        preserve_existing_prices_for_invalid_update(card_data, existing)
    has_api_image = bool(card_data.get("images_small") or card_data.get("images_large"))
    if existing:
        update_existing_card(
            existing,
            card_data,
            partial=partial,
            metadata_only=metadata_only,
        )
        if has_api_image:
            existing.custom_image_url = None
            db.query(ImageCache).filter(ImageCache.image_key.in_([
                f"card:{existing.id}:small:custom",
                f"card:{existing.id}:large:custom",
            ])).delete(synchronize_session=False)
    else:
        if metadata_only:
            card_data = {
                key: value
                for key, value in card_data.items()
                if not _is_price_state_field(key)
            }
        existing = Card(**card_data)
        db.add(existing)
    return existing
